CORE = '''

def permission_check(tool: Tool, args: dict) -> str:
    """Return "allow", "ask", or "deny" for a tool call.

    Override with your product's permission rules (see s03). Default is
    conservative: anything marked "ask" requires human consent.
    """
    if tool.permission == "deny":
        return "deny"
    if tool.permission == "ask":
        answer = input(f"  [permission] Allow {tool.name}({str(args)[:80]})? [y/N] ")
        return "allow" if answer.strip().lower() in {"y", "yes"} else "deny"
    return "allow"


SYSTEM_PROMPT = f"""You are a coding agent working in {WORKDIR}.

Rules:
{rules}

Tools: {tool_names}.
"""


def _backoff(attempt: int) -> float:
    return CONFIG["base_delay_seconds"] * (2 ** attempt)


def call_model(messages: list[dict]) -> Any:
    """Call the model with retry on transient errors and timeout."""
    last_error: Exception | None = None
    for attempt in range(CONFIG["max_retries"]):
        try:
            return client.messages.create(
                model=CONFIG["model"],
                system=SYSTEM_PROMPT,
                messages=messages,
                tools=TOOL_DEFS,
                max_tokens=CONFIG["max_tokens"],
                timeout=CONFIG["timeout_seconds"],
            )
        except (APITimeoutError, APIConnectionError, APIStatusError) as exc:
            last_error = exc
            delay = _backoff(attempt)
            LOG.warning("model call failed (attempt %d/%d): %s; retry in %.1fs",
                        attempt + 1, CONFIG["max_retries"], exc, delay)
            time.sleep(delay)
    raise RuntimeError(f"Model call failed after {CONFIG['max_retries']} attempts: {last_error}")


def record_trajectory(entry: dict) -> None:
    """Append one step to the trajectory log (training signal for the future)."""
    try:
        TRAJECTORY_DIR.mkdir(parents=True, exist_ok=True)
        path = TRAJECTORY_DIR / f"trajectory-{time.strftime('%Y%m%d')}.jsonl"
        with path.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(entry, ensure_ascii=True) + "\\n")
    except Exception as exc:  # noqa: BLE001
        LOG.warning("failed to record trajectory: %s", exc)


def agent_loop(prompt: str, history: list[dict] | None = None) -> str:
    history = history if history is not None else []
    history.append({"role": "user", "content": prompt})

    while True:
        response = call_model(history)
        history.append({"role": "assistant", "content": response.content})

        tool_calls = [b for b in response.content if getattr(b, "type", None) == "tool_use"]
        if not tool_calls:
            return "".join(
                b.text for b in response.content if getattr(b, "type", None) == "text"
            )

        results = []
        for block in tool_calls:
            tool = TOOL_SPECS.get(block.name)
            if tool is None:
                output = f"Unknown tool: {block.name}"
            else:
                try:
                    args = _validate_input(tool, dict(block.input))
                    decision = permission_check(tool, args)
                    if decision == "deny":
                        output = f"Permission denied for {tool.name}"
                    else:
                        output = tool.handler(**args)
                except Exception as exc:  # noqa: BLE001
                    output = f"Error: {type(exc).__name__}: {exc}"
                record_trajectory({
                    "ts": time.time(),
                    "tool": block.name,
                    "input": block.input,
                    "output": output[:1000],
                })
            LOG.info("tool=%s output=%s", block.name, output[:120])
            results.append({
                "type": "tool_result",
                "tool_use_id": block.id,
                "content": output,
            })

        history.append({"role": "user", "content": results})


def _shutdown(signum, _frame):
    LOG.info("received signal %s, shutting down", signum)
    sys.exit(128 + signum)


def main() -> None:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s %(message)s",
    )
    signal.signal(signal.SIGTERM, _shutdown)
    signal.signal(signal.SIGINT, _shutdown)

    LOG.info("agent started; model=%s workdir=%s", CONFIG["model"], WORKDIR)
    print(f"Agent ready. Model: {CONFIG['model']}. Type 'q' to quit.\\n")

    history: list[dict] = []
    while True:
        try:
            query = input(">> ").strip()
        except (EOFError, KeyboardInterrupt):
            break
        if query in {"q", "quit", "exit", ""}:
            break
        try:
            print(agent_loop(query, history))
        except Exception as exc:  # noqa: BLE001
            LOG.error("agent loop failed: %s", exc)
            print(f"Error: {exc}")
        print()


if __name__ == "__main__":
    main()
'''


LEVEL_DESCRIPTIONS = {
    0: "agent loop + bash",
    1: "4 tools, production base",
    2: "+ TodoWrite planning",
    3: "+ Subagent",
    4: "+ Skill loading",
}


def build_agent_source(name: str, level: int) -> str:
    """Assemble the full agent.py source for a name and level."""
    handlers = [HANDLER_BASH]
    if level >= 1:
        handlers.append(HANDLER_READ_WRITE_EDIT)
    if level >= 2:
        handlers.append(HANDLER_TODO)
    if level >= 3:
        handlers.append(HANDLER_SUBAGENT)
    if level >= 4:
        handlers.append(HANDLER_SKILL)

    source = COMMON_HEADER.format(
        name=name, level=level, level_desc=LEVEL_DESCRIPTIONS[level]
    )
    source += "".join(handlers)
    source += "\n\nTOOL_SPECS: dict[str, Tool] = {\n" + tool_specs_for(level) + "\n}\n"
    source += (
        "\nTOOL_DEFS = [\n"
        "    {\"name\": t.name, \"description\": t.description, \"input_schema\": t.input_schema}\n"
        "    for t in TOOL_SPECS.values()\n"
        "]\n"
    )
    # fill the CORE placeholders: {rules} and {tool_names}
    source += CORE.replace("{rules}", system_rules_for(level)).replace(
        "{tool_names}", tool_names_for(level)
    )
    return source


