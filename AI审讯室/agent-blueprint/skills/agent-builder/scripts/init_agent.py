def create_agent(name: str, level: int, output_dir: Path) -> None:
    if level not in LEVEL_DESCRIPTIONS:
        print(f"Error: level must be one of {sorted(LEVEL_DESCRIPTIONS)}")
        sys.exit(1)

    agent_dir = output_dir / name
    agent_dir.mkdir(parents=True, exist_ok=True)

    (agent_dir / "agent.py").write_text(build_agent_source(name, level), encoding="utf-8")
    (agent_dir / ".env.example").write_text(ENV_TEMPLATE, encoding="utf-8")
    (agent_dir / "config.example.yaml").write_text(CONFIG_TEMPLATE, encoding="utf-8")
    (agent_dir / "requirements.txt").write_text(REQUIREMENTS_TEMPLATE, encoding="utf-8")
    (agent_dir / "README.md").write_text(
        README_TEMPLATE.format(name=name, level=level, level_desc=LEVEL_DESCRIPTIONS[level]),
        encoding="utf-8",
    )

    print(f"Created production Agent project '{name}' at {agent_dir}")
    print("Files: agent.py, config.example.yaml, .env.example, requirements.txt, README.md")
    print("\nNext steps:")
    print(f"  1. cd {agent_dir}")
    print("  2. pip install -r requirements.txt")
    print("  3. cp .env.example .env   # fill in ANTHROPIC_API_KEY")
    print("  4. python agent.py")


