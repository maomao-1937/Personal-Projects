def system_rules_for(level: int) -> str:
    rules = ["- Prefer action over explanation.",
             "- Never invent file paths; read first if unsure.",
             "- After finishing, summarize what changed."]
    if level >= 2:
        rules.append("- For multi-step work, call todo_write first to lay out the plan.")
    if level >= 3:
        rules.append("- For noisy or isolated subtasks, use spawn_subagent instead of inline work.")
    if level >= 4:
        rules.append("- List skills with list_skills, then load_skill(name) only when relevant.")
    return "\n".join(rules)


def tool_names_for(level: int) -> str:
    names = ["bash"]
    if level >= 1:
        names += ["read_file", "write_file", "edit_file"]
    if level >= 2:
        names.append("todo_write")
    if level >= 3:
        names.append("spawn_subagent")
    if level >= 4:
        names += ["list_skills", "load_skill"]
    return ", ".join(names)


