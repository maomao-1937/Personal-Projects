export type EditOptions = {
  customBreed?: string;
  style?: Style;
  freedom?: "head" | "scene";
};
export function compilePrompt(
  breed: string,
  extra: string,
  options: EditOptions = {},
) {
  const target = getBreed(breed);
  const name =
    breed === "custom"
      ? options.customBreed?.trim() || "用户指定的犬种"
      : target?.label || "柴犬";
  const appearance =
    target?.appearance || "依据用户指定犬种呈现可信的毛发、耳形和口鼻结构";
  const style = {
    photo: "自然摄影质感，与原图镜头、景深、清晰度一致",
    paint: "有自然笔触和体积感的绘画质感，主体结构与原图一致",
    toon: "精细 3D 角色质感，柔和材质与可信体积，保持原人物构图",
  }[options.style || "photo"];
  return `【编辑任务】以输入人像为唯一构图基准，把主要人物的头部变成${name}${target ? `（${target.english}）` : ""}的犬头。人物仍保有人类身体和手部。\n【犬种造型】${appearance}。头部尺寸与原人物肩宽协调，耳朵完整，颈部过渡自然。\n【画面质感】${style}。光源方向和阴影关系连贯。\n【保留与修改】${options.freedom === "scene" ? "允许按用户明确要求调整配饰与场景；没有要求改变的身体、姿势、服装和背景保持原样。" : "只修改头部及必要的颈部融合区域，身体、手部、姿势、服装、背景和构图保持原样。"}头部朝向、眼镜与帽子默认保留；若用户明确要求修改这些头部细节，以该要求替换对应默认约束，不同时执行相反要求。眼镜按新口鼻自然适配。表情优先级：用户本次明确要求最高；用户要求保留原表情时遵从；否则采用下方犬种造型建议。相反的表情约束不同时执行。\n【表情建议】${target ? breedExpressions[target.id] : "神态自然，嘴型与舌头状态按用户要求确定"}。这是可调整的创作建议，不代表犬种性格；嘴型、舌头长度、露出程度与偏侧应自然可信，不统一使用张嘴长吐舌。\n【本次要求】${extra.trim() || "采用上述造型建议，不额外添加配饰。"}\n【质量边界】避免人脸残留、额外耳朵、变成完整四足犬、人类手部变爪、重复人物、悬浮头部和明显拼贴边缘。`;
}
